import subprocess
import sys


def run(args, cwd):
    return subprocess.run([sys.executable, "-m", "env_sentry.cli", *args],
                          cwd=cwd, capture_output=True, text=True)


ENV = """# app config
DATABASE_URL=postgres://user:pw@host/db
DEBUG=true
PORT=3000
JWT_SECRET=abc123realvalue
"""


def test_sync_writes_placeholders_and_keeps_comments(tmp_path):
    (tmp_path / ".env").write_text(ENV)
    result = run(["sync"], cwd=tmp_path)
    assert result.returncode == 0
    text = (tmp_path / ".env.example").read_text()
    assert "abc123realvalue" not in text
    assert "# app config" in text
    assert "JWT_SECRET=your_jwt_secret_here" in text
    assert "PORT=3000" in text
    assert "DEBUG=false" in text
    assert text.startswith("# Auto-generated by env-sentry")


def test_sync_no_header_and_dry_run(tmp_path):
    (tmp_path / ".env").write_text(ENV)
    result = run(["sync", "--dry-run", "--no-header"], cwd=tmp_path)
    assert "Auto-generated" not in result.stdout
    assert not (tmp_path / ".env.example").exists()


def test_sync_check_detects_drift(tmp_path):
    (tmp_path / ".env").write_text(ENV)
    assert run(["sync", "--check"], cwd=tmp_path).returncode == 1
    run(["sync"], cwd=tmp_path)
    assert run(["sync", "--check"], cwd=tmp_path).returncode == 0

    (tmp_path / ".env").write_text(ENV + "NEW_KEY=x\n")
    result = run(["sync", "--check"], cwd=tmp_path)
    assert result.returncode == 1
    assert "NEW_KEY" in result.stdout


def test_sync_merge_keeps_extra_example_keys(tmp_path):
    (tmp_path / ".env").write_text("A=1\n")
    (tmp_path / ".env.example").write_text("A=placeholder\nLEGACY=keepme\n")
    run(["sync"], cwd=tmp_path)
    assert "LEGACY" not in (tmp_path / ".env.example").read_text()

    (tmp_path / ".env.example").write_text("A=placeholder\nLEGACY=keepme\n")
    result = run(["sync", "--merge"], cwd=tmp_path)
    assert "Kept 1 existing key" in result.stdout
    assert "LEGACY=keepme" in (tmp_path / ".env.example").read_text()


def test_sync_missing_env(tmp_path):
    result = run(["sync"], cwd=tmp_path)
    assert result.returncode == 1
    assert "not found" in result.stdout


def test_sync_output_passes_check(tmp_path):
    (tmp_path / ".env").write_text(ENV)
    (tmp_path / ".gitignore").write_text(".env\n")
    run(["sync"], cwd=tmp_path)
    assert run(["check"], cwd=tmp_path).returncode == 0


def test_sync_refuses_to_wipe_template_from_empty_env(tmp_path):
    (tmp_path / ".env").write_text("# just a comment\n")
    (tmp_path / ".env.example").write_text("API_KEY=your_api_key_here\n")
    result = run(["sync"], cwd=tmp_path)
    assert result.returncode == 1
    assert "has no KEY=value pairs" in result.stdout
    assert (tmp_path / ".env.example").read_text() == "API_KEY=your_api_key_here\n"

    result = run(["sync", "--force"], cwd=tmp_path)
    assert result.returncode == 0
    assert (tmp_path / ".env.example").read_text() != "API_KEY=your_api_key_here\n"


def test_sync_check_compares_key_coverage_not_formatting(tmp_path):
    (tmp_path / ".env").write_text("API_KEY=realvalue123\nPORT=8080\n")
    (tmp_path / ".env.example").write_text(
        "# hand-written template\nAPI_KEY=your_api_key_here\nPORT=8080\n"
    )
    result = run(["sync", "--check"], cwd=tmp_path)
    assert result.returncode == 0
    assert "covers every key" in result.stdout
